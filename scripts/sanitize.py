"""Scan every tracked-or-untracked file in the repo for personal data and secret-like strings.

Writes SANITIZE.md with the patterns checked and every hit. Exit code 1 if any hit.
Usage: python scripts/sanitize.py

The personal terms to search for are read from a file OUTSIDE the repo, so the list itself is
never published: set SANITIZE_TERMS=/path/to/terms.txt (one term per line, case-insensitive).
Without it only the generic patterns run.
"""
import os
import pathlib
import re
import sys

repo = pathlib.Path(__file__).resolve().parent.parent
skip_dirs = {".git"}
skip_files = {"SANITIZE.md"}

# Generic patterns. Placeholders such as <YOUR_API_KEY> and the documentation-only
# address domain example.com are allowed by the regexes below.
generic = {
    "email address": r"[A-Za-z0-9._%+-]+@(?!example\.com\b)[A-Za-z0-9.-]+\.[A-Za-z]{2,}",
    "NVIDIA key (nvapi-)": r"nvapi-[A-Za-z0-9_-]{8,}",
    "OpenAI/Anthropic style key (sk-)": r"\bsk-(?:ant-)?[A-Za-z0-9_-]{16,}",
    "GitHub token (ghp_/gho_/ghs_/github_pat_)": r"\b(?:ghp|gho|ghs|ghu|github_pat)_[A-Za-z0-9_]{16,}",
    "Google API key (AIza)": r"AIza[0-9A-Za-z_-]{20,}",
    "Slack token (xoxb-/xoxp-)": r"xox[abpr]-[A-Za-z0-9-]{8,}",
    "Bearer token": r"Bearer\s+[A-Za-z0-9._~+/-]{12,}",
    "IPv4 address": r"\b(?:25[0-5]|2[0-4]\d|1?\d?\d)(?:\.(?:25[0-5]|2[0-4]\d|1?\d?\d)){3}\b",
    "Windows user path": r"[A-Za-z]:\\\\?Users\\\\?",
    "WSL Windows user path": r"/mnt/[a-z]/Users/",
    "Linux home of a named user": r"/home/(?!<user>|\$USER|user\b)[a-z][a-z0-9_-]*",
    "macOS home of a named user": r"/Users/(?!<you>|<user>|\$USER|user\b)[A-Za-z][A-Za-z0-9_-]*",
    "em dash": chr(0x2014),
}
# IPv4 hits that are not addresses of a machine: version-like strings are rare in 4 parts,
# but loopback, the unspecified address and documentation ranges are allowed.
ip_allow = re.compile(r"^(127\.0\.0\.1|0\.0\.0\.0|192\.0\.2\.\d+|198\.51\.100\.\d+|203\.0\.113\.\d+)$")

patterns = {k: re.compile(v) for k, v in generic.items()}
terms_file = os.environ.get("SANITIZE_TERMS")
n_terms = 0
if terms_file:
    for i, t in enumerate(pathlib.Path(terms_file).read_text(encoding="utf-8").splitlines()):
        t = t.strip()
        if t and not t.startswith("#"):
            n_terms += 1
            rx = re.escape(t)
            if re.match(r"\w", t) and re.search(r"\w$", t):
                rx = rf"\b{rx}\b"  # whole words only, so short names do not hit inside other words
            patterns[f"private term #{i + 1}"] = re.compile(rx, re.I)

hits = []
files = 0
for p in sorted(repo.rglob("*")):
    if not p.is_file() or any(part in skip_dirs for part in p.relative_to(repo).parts) or p.name in skip_files:
        continue
    files += 1
    rel = p.relative_to(repo).as_posix()
    # file names count too
    for name, rx in patterns.items():
        if rx.search(rel):
            hits.append((rel, 0, name))
    try:
        text = p.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        hits.append((rel, 0, "binary or non-UTF-8 file (check by hand)"))
        continue
    for n, line in enumerate(text.splitlines(), 1):
        for name, rx in patterns.items():
            for m in rx.finditer(line):
                if name == "IPv4 address" and ip_allow.match(m.group(0)):
                    continue
                hits.append((rel, n, name))

out = ["# Sanitizer report", "", "Generated by `scripts/sanitize.py`.", "",
       f"- Files scanned: {files}",
       f"- Generic patterns: {len(generic)} ({', '.join(generic)})",
       f"- Private terms from a list kept outside the repo: {n_terms}",
       f"- Hits: {len(hits)}", ""]
if hits:
    out += ["| File | Line | Pattern |", "|---|---|---|"] + [f"| {f} | {n} | {k} |" for f, n, k in hits]
else:
    out.append("No hits.")
(repo / "SANITIZE.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{files} files, {n_terms} private terms, {len(hits)} hits")
for h in hits[:50]:
    print("HIT", *h)
sys.exit(1 if hits else 0)
